#!/usr/bin/env node
// scripts/check-schema-additive.mjs — a schema change may only ADD
// (MKT-0; MARKET_STRATEGY.md 2.3 stack constraints and 7 item 11; SM-7).
//
// Compares two Prisma schema folders with `prisma migrate diff`, datamodel to
// datamodel, prints the SQL and exits 1 when the SQL does anything but add:
// DROP TABLE, DROP COLUMN, DROP INDEX, ALTER COLUMN ... TYPE, SET NOT NULL,
// DROP DEFAULT, RENAME, any other DROP, a changed default, a required column
// with no default, or a statement that is not CREATE TABLE / ADD COLUMN /
// CREATE INDEX / ADD CONSTRAINT.
//
// It also compares the two folders as text for one thing Prisma cannot see: the
// type inside Unsupported("...") of a field both folders have. Prisma prints an
// empty migration for halfvec(1024) -> halfvec(1536), and db push applies
// nothing, so schema and database would drift apart. That is reported as
// `unsupported_type_changed`.
//
// KNOWN_DRIFT (docs/jobright-clone/schema-diffs/KNOWN_DRIFT.md) is used with
// --sql only. The pairs come from introspection of a database, so a diff between
// two schema folders can never contain one honestly. A pair is excused only when
// its CREATE INDEX is the definition recorded in the second column of the table;
// the same index name with other columns, another index type or no operator
// class is a real change and fails.
//
// No database: both sides of the diff are schema folders, and the child
// process gets a closed-port placeholder for DATABASE_URL / DIRECT_DATABASE_URL
// so the Prisma config can never hand it a real connection string. This script
// never runs db push, migrate dev / deploy / reset, db execute or db pull.
//
//   node scripts/check-schema-additive.mjs
//       "from" = server/prisma/schema at the merge base of HEAD and
//       feat/jobright-clone (exported to a temp folder), "to" = the working folder
//   --base <git ref>     another "from" commit
//   --from-dir <dir>     a schema folder as "from" instead of a git ref
//   --to-dir <dir>       another "to" folder (default server/prisma/schema)
//   --sql <file | ->     classify SQL that already exists instead of running Prisma,
//                        e.g. the output of a database-to-schema diff the orchestrator
//                        made (server/prisma/sql/README.md steps 3 and 5). The only
//                        mode that applies KNOWN_DRIFT.
//   --out <file>         write the SQL below the marker line of <file>, keeping the
//                        reviewer header above it (docs/jobright-clone/schema-diffs/*.sql)
//   --check <file>       exit 1 when the generated part of <file> is not what the diff
//                        from the base commit recorded in the file prints today
//   --quiet              do not print the SQL
//   --root <dir>         run against another checkout
//
// The classifier, the KNOWN_DRIFT reader and the Unsupported comparison are
// exported as pure functions; their tests are in
// server/prisma/__tests__/checkSchemaAdditive.test.ts.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SCHEMA_DIR = 'server/prisma/schema';
export const KNOWN_DRIFT_PATH = 'docs/jobright-clone/schema-diffs/KNOWN_DRIFT.md';
export const DEFAULT_BASE_BRANCH = 'feat/jobright-clone';
/** Everything below this line of a schema-diffs/*.sql file is written by --out. */
export const GENERATED_MARKER = '-- >>> generated by scripts/check-schema-additive.mjs: do not edit below this line >>>';
/** A connection string nothing listens on: the diff needs no database and must not find one. */
export const NO_DATABASE_URL = 'postgresql://noop:noop@127.0.0.1:1/noop';

/**
 * Rules that make a diff non-additive. `drop_table` … `rename` are the seven
 * named in the MKT-0 item; the rest close the gaps around them. All but the
 * last are read from the SQL; `unsupported_type_changed` is read from the two
 * schema folders (unsupportedTypeChanges), because no SQL is printed for it.
 */
export const RULES = Object.freeze({
  drop_table: 'DROP TABLE removes a table',
  drop_column: 'DROP COLUMN removes a column',
  drop_index: 'DROP INDEX removes an index (only a KNOWN_DRIFT pair may do that)',
  alter_column_type: 'ALTER COLUMN ... TYPE changes the type of an existing column',
  set_not_null: 'SET NOT NULL tightens an existing column',
  drop_default: 'DROP DEFAULT changes an existing column',
  rename: 'RENAME: nothing is renamed in an additive change',
  drop_other: 'DROP of a constraint, a NOT NULL, a type or anything else',
  set_default: 'SET DEFAULT changes the default of an existing column',
  required_column_without_default: 'ADD COLUMN ... NOT NULL without DEFAULT fails on a table that has rows',
  not_additive: 'not CREATE TABLE, ADD COLUMN, CREATE INDEX, ADD CONSTRAINT, CREATE TYPE or CREATE EXTENSION',
  unsupported_type_changed:
    'the declared type of a field changed and one side is Unsupported("..."). For a changed raw type (a vector dimension, another type name) Prisma prints no SQL and db push applies nothing, so schema and database would drift apart: add a new column instead',
});

/** Additive statements that can still fail on existing rows. Reported, never fatal. */
export const WARNINGS = Object.freeze({
  unique_on_existing_table: 'a unique index on a table that already has rows fails when two rows share the key',
  constraint_on_existing_table: 'a constraint on a table that already has rows fails when a row violates it',
});

// ── SQL text ────────────────────────────────────────────────────────────────

/**
 * Split SQL into statements. Comments are dropped; a semicolon inside a string,
 * a quoted name or a dollar-quoted body does not end a statement.
 * @param {string} sql
 * @returns {{ text: string, line: number }[]} `line` is the 1-based line the statement starts on
 */
export function splitSqlStatements(sql) {
  const statements = [];
  let text = '';
  let startLine = 0;
  let line = 1;
  const push = () => {
    const trimmed = text.trim();
    if (trimmed) statements.push({ text: trimmed, line: startLine });
    text = '';
    startLine = 0;
  };
  const take = (chunk) => {
    if (!startLine && /\S/.test(chunk)) startLine = line;
    text += chunk;
    for (const ch of chunk) if (ch === '\n') line += 1;
  };
  const skip = (chunk) => {
    for (const ch of chunk) if (ch === '\n') line += 1;
  };

  let i = 0;
  while (i < sql.length) {
    const ch = sql[i];
    const next = sql[i + 1];
    if (ch === '-' && next === '-') {
      const end = sql.indexOf('\n', i);
      const stop = end === -1 ? sql.length : end;
      skip(sql.slice(i, stop));
      i = stop;
    } else if (ch === '/' && next === '*') {
      const end = sql.indexOf('*/', i + 2);
      const stop = end === -1 ? sql.length : end + 2;
      skip(sql.slice(i, stop));
      text += ' ';
      i = stop;
    } else if (ch === "'" || ch === '"') {
      let j = i + 1;
      while (j < sql.length) {
        if (sql[j] === ch && sql[j + 1] === ch) j += 2;
        else if (sql[j] === ch) break;
        else j += 1;
      }
      take(sql.slice(i, Math.min(j + 1, sql.length)));
      i = j + 1;
    } else if (ch === '$' && /^\$[A-Za-z_]*\$/.test(sql.slice(i, i + 64))) {
      const tag = /^\$[A-Za-z_]*\$/.exec(sql.slice(i, i + 64))[0];
      const end = sql.indexOf(tag, i + tag.length);
      const stop = end === -1 ? sql.length : end + tag.length;
      take(sql.slice(i, stop));
      i = stop;
    } else if (ch === ';') {
      push();
      i += 1;
    } else {
      take(ch);
      i += 1;
    }
  }
  push();
  return statements;
}

/** Upper-cased keyword skeleton: strings become '', quoted names become "", whitespace collapses. */
function skeleton(statement) {
  return statement
    .replace(/\$([A-Za-z_]*)\$[\s\S]*?\$\1\$/g, "''")
    .replace(/'(?:[^']|'')*'/g, "''")
    .replace(/"(?:[^"]|"")*"/g, '""')
    .replace(/\s+/g, ' ')
    .trim()
    .toUpperCase();
}

/** Top-level comma-separated clauses of an ALTER TABLE body (commas inside parentheses stay). */
function alterClauses(body) {
  const clauses = [];
  let depth = 0;
  let current = '';
  for (const ch of body) {
    if (ch === '(') depth += 1;
    if (ch === ')') depth -= 1;
    if (ch === ',' && depth === 0) {
      clauses.push(current.trim());
      current = '';
    } else current += ch;
  }
  if (current.trim()) clauses.push(current.trim());
  return clauses;
}

const firstQuotedName = (statement, pattern) => pattern.exec(statement)?.[1] ?? null;

// ── KNOWN_DRIFT ─────────────────────────────────────────────────────────────

/**
 * The rows of the table in KNOWN_DRIFT.md. `name` is the code span in the FIRST
 * cell. `create` is the code span of the SECOND cell that starts with CREATE:
 * the statement as the diff prints it, with … (or ...) in place of the index
 * name and its table, e.g. `CREATE INDEX … ("sourceBoard", "externalId" text_pattern_ops)`.
 * A row without one has `create: null` and excuses nothing. Prose, the header
 * row and the third cell name nothing.
 * @param {string} markdown
 * @returns {{ name: string, create: string | null }[]}
 */
export function parseKnownDrift(markdown) {
  const entries = [];
  for (const raw of markdown.split('\n')) {
    const line = raw.trim();
    if (!line.startsWith('|')) continue;
    const cells = line.split('|');
    const name = /^`([A-Za-z0-9_]+)`$/.exec(cells[1]?.trim() ?? '')?.[1];
    if (!name || entries.some((e) => e.name === name)) continue;
    const spans = [...(cells[2] ?? '').matchAll(/`([^`]+)`/g)].map((m) => m[1].trim());
    entries.push({ name, create: spans.find((span) => /^CREATE\b/.test(span)) ?? null });
  }
  return entries;
}

/** One spelling for comparison: single spaces, none around ( ) and commas, no closing semicolon. */
const canonSql = (sql) =>
  sql
    .replace(/\s+/g, ' ')
    .replace(/ ?([(),]) ?/g, '$1')
    .trim()
    .replace(/;$/, '');

const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Is `statement` the CREATE INDEX that the KNOWN_DRIFT row records? The … of the
 * recorded form stands for the quoted index name and `ON "<table>"`, and for
 * nothing else: the index method, the column list, every operator class and the
 * absence of a WHERE clause must be exactly what the row says.
 * @param {string} statement
 * @param {{ name: string, create: string | null }} entry
 */
export function knownDriftCreateMatches(statement, entry) {
  if (!entry?.create) return false;
  const parts = entry.create.split(/…|\.\.\./);
  if (parts.length !== 2) return false;
  const head = canonSql(parts[0]);
  const tail = canonSql(parts[1]);
  if (!/^CREATE (UNIQUE )?INDEX$/.test(head) || !tail) return false;
  const shape = new RegExp(
    `^${escapeRegExp(head)} (?:CONCURRENTLY )?(?:IF NOT EXISTS )?"${escapeRegExp(entry.name)}" ON (?:ONLY )?(?:"[^"]+"\\.)?"[^"]+" ?${escapeRegExp(tail)}$`,
  );
  return shape.test(canonSql(statement));
}

// ── classifier ──────────────────────────────────────────────────────────────

/**
 * Decide whether SQL (the --script output of `prisma migrate diff`) only adds.
 *
 * A KNOWN_DRIFT pair is the DROP INDEX and the CREATE INDEX of one listed index
 * name in the same SQL, where the CREATE INDEX is the recorded definition
 * (knownDriftCreateMatches). Both statements are set aside. A listed index that
 * is dropped and not created again, or created with another definition, is a
 * real change and fails. Pass `knownDrift` for a database diff only.
 *
 * @param {string} sql
 * @param {{ knownDrift?: ({ name: string, create: string | null } | string)[] }} [options]
 *   rows from parseKnownDrift (a bare name has no recorded definition and excuses nothing)
 * @returns {{
 *   ok: boolean,
 *   statements: { text: string, line: number }[],
 *   violations: { rule: string, statement: string, line: number }[],
 *   ignored: { text: string, line: number }[],
 *   warnings: { rule: string, statement: string, line: number }[],
 * }}
 */
export function classifyAdditive(sql, options = {}) {
  const knownDrift = (options.knownDrift ?? []).map((entry) => (typeof entry === 'string' ? { name: entry, create: null } : entry));
  const statements = splitSqlStatements(sql);

  const droppedIndex = (s) => firstQuotedName(s.text, /^DROP\s+INDEX\s+(?:CONCURRENTLY\s+)?(?:IF\s+EXISTS\s+)?"([^"]+)"\s*$/i);
  const createdIndex = (s) =>
    firstQuotedName(s.text, /^CREATE\s+(?:UNIQUE\s+)?INDEX\s+(?:CONCURRENTLY\s+)?(?:IF\s+NOT\s+EXISTS\s+)?"([^"]+)"\s+ON\b/i);

  const ignored = [];
  const ignoredSet = new Set();
  for (const entry of knownDrift) {
    const drops = statements.filter((s) => droppedIndex(s) === entry.name);
    const creates = statements.filter((s) => createdIndex(s) === entry.name);
    if (drops.length === 1 && creates.length === 1 && knownDriftCreateMatches(creates[0].text, entry)) {
      for (const s of [drops[0], creates[0]]) {
        ignoredSet.add(s);
        ignored.push(s);
      }
    }
  }
  ignored.sort((a, b) => a.line - b.line);

  const createdTables = new Set();
  for (const s of statements) {
    const table = firstQuotedName(s.text, /^CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?"([^"]+)"/i);
    if (table) createdTables.add(table);
  }

  const violations = [];
  const warnings = [];
  for (const s of statements) {
    if (ignoredSet.has(s)) continue;
    const k = skeleton(s.text);
    const rules = new Set();
    const warn = new Set();

    if (/\bDROP TABLE\b/.test(k)) rules.add('drop_table');
    if (/\bDROP COLUMN\b/.test(k)) rules.add('drop_column');
    if (/\bDROP INDEX\b/.test(k)) rules.add('drop_index');
    if (/\bALTER COLUMN "" (SET DATA )?TYPE\b/.test(k)) rules.add('alter_column_type');
    if (/\bSET NOT NULL\b/.test(k)) rules.add('set_not_null');
    if (/\bDROP DEFAULT\b/.test(k)) rules.add('drop_default');
    if (/\bRENAME\b/.test(k)) rules.add('rename');
    if (/\bDROP (?!TABLE\b|COLUMN\b|INDEX\b|DEFAULT\b)/.test(k)) rules.add('drop_other');
    if (/\bALTER COLUMN "" SET DEFAULT\b/.test(k)) rules.add('set_default');

    if (/^ALTER TABLE\b/.test(k)) {
      const body = k.replace(/^ALTER TABLE (ONLY )?(IF EXISTS )?("")(\.(""))? ?/, '');
      const table = firstQuotedName(s.text, /^ALTER\s+TABLE\s+(?:ONLY\s+)?(?:IF\s+EXISTS\s+)?"([^"]+)"/i);
      for (const clause of alterClauses(body)) {
        if (/^ADD COLUMN\b/.test(clause)) {
          if (/\bNOT NULL\b/.test(clause) && !/\bDEFAULT\b/.test(clause) && !/\bGENERATED\b/.test(clause)) {
            rules.add('required_column_without_default');
          }
        } else if (/^ADD CONSTRAINT\b/.test(clause)) {
          if (table && !createdTables.has(table)) warn.add('constraint_on_existing_table');
        } else if (rules.size === 0) {
          rules.add('not_additive');
        }
      }
    } else if (/^CREATE UNIQUE INDEX\b/.test(k)) {
      const table = firstQuotedName(s.text, /\bON\s+(?:ONLY\s+)?"([^"]+)"/i);
      if (table && !createdTables.has(table)) warn.add('unique_on_existing_table');
    } else if (
      !/^CREATE TABLE\b/.test(k) &&
      !/^CREATE INDEX\b/.test(k) &&
      !/^CREATE TYPE\b/.test(k) &&
      !/^CREATE EXTENSION\b/.test(k) &&
      !/^ALTER TYPE (""\.)?"" ADD VALUE\b/.test(k) &&
      rules.size === 0
    ) {
      rules.add('not_additive');
    }

    for (const rule of rules) violations.push({ rule, statement: s.text, line: s.line });
    for (const rule of warn) warnings.push({ rule, statement: s.text, line: s.line });
  }

  return { ok: violations.length === 0, statements, violations, ignored, warnings };
}

// ── Unsupported("...") fields ───────────────────────────────────────────────

/** A schema line without its `//` or `///` comment (a `//` inside a string stays). */
function stripSchemaComment(line) {
  let inString = false;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (inString && ch === '\\') i += 1;
    else if (ch === '"') inString = !inString;
    else if (!inString && ch === '/' && line[i + 1] === '/') return line.slice(0, i);
  }
  return line;
}

/**
 * The type of every model field in Prisma schema text, as written:
 * 'RAJob.searchTsv' -> 'Unsupported("tsvector")?', 'RAJob.title' -> 'String'.
 * @param {string} schemaText one file, or several joined
 * @returns {Map<string, string>}
 */
export function schemaFieldTypes(schemaText) {
  const types = new Map();
  let model = null;
  for (const raw of schemaText.split('\n')) {
    const line = stripSchemaComment(raw).trim();
    if (!line) continue;
    const open = /^model\s+(\w+)\s*\{$/.exec(line);
    if (open) model = open[1];
    else if (line === '}') model = null;
    else if (model && !line.startsWith('@@')) {
      const field = /^(\w+)\s+(Unsupported\("(?:[^"\\]|\\.)*"\)(?:\?|\[\])?|\S+)/.exec(line);
      if (field) types.set(`${model}.${field[1]}`, field[2]);
    }
  }
  return types;
}

/**
 * Fields that both schemas have and whose type differs where one side is
 * Unsupported("..."): a changed vector dimension, another raw type, a dropped
 * `?`, or a move into or out of Unsupported. `prisma migrate diff` prints no
 * SQL for these and `prisma db push` applies nothing. A new field and a removed
 * field are not listed here: the SQL shows them (ADD COLUMN, DROP COLUMN).
 * @param {string} fromSchemaText
 * @param {string} toSchemaText
 * @returns {{ field: string, from: string, to: string }[]}
 */
export function unsupportedTypeChanges(fromSchemaText, toSchemaText) {
  const from = schemaFieldTypes(fromSchemaText);
  const to = schemaFieldTypes(toSchemaText);
  const isUnsupported = (type) => type.startsWith('Unsupported(');
  const changes = [];
  for (const [field, was] of from) {
    const now = to.get(field);
    if (now === undefined || now === was) continue;
    if (isUnsupported(was) || isUnsupported(now)) changes.push({ field, from: was, to: now });
  }
  return changes;
}

/**
 * The classification with the Unsupported changes added as violations (line 0: they are in the schema, not in the SQL).
 * @param {ReturnType<typeof classifyAdditive>} result
 * @param {{ field: string, from: string, to: string }[]} changes
 */
export function withUnsupportedChanges(result, changes) {
  if (!changes || changes.length === 0) return result;
  const violations = [
    ...result.violations,
    ...changes.map((c) => ({ rule: 'unsupported_type_changed', statement: `${c.field}: ${c.from} -> ${c.to}`, line: 0 })),
  ];
  return { ...result, ok: false, violations };
}

// ── schema-diffs/*.sql files ────────────────────────────────────────────────

/**
 * A schema-diffs file written by --out: reviewer header, marker, base line, SQL.
 * @param {string} text
 * @returns {{ header: string, base: string | null, sql: string } | null} null when the marker is missing
 */
export function splitGeneratedFile(text) {
  const at = text.indexOf(GENERATED_MARKER);
  if (at === -1) return null;
  const header = text.slice(0, at);
  const rest = text.slice(at + GENERATED_MARKER.length).replace(/^\n/, '');
  const baseMatch = /^-- base: ([0-9a-f]{40})\b[^\n]*\n\n?/.exec(rest);
  return {
    header,
    base: baseMatch ? baseMatch[1] : null,
    sql: baseMatch ? rest.slice(baseMatch[0].length) : rest,
  };
}

/** @param {{ header: string, base: string | null, sql: string }} parts */
export function renderGeneratedFile({ header, base, sql }) {
  const baseLine = base ? `-- base: ${base} (${SCHEMA_DIR} at that commit) -> the schema folder of this commit\n\n` : '';
  return `${header}${GENERATED_MARKER}\n${baseLine}${sql.endsWith('\n') ? sql : `${sql}\n`}`;
}

// ── running the diff ────────────────────────────────────────────────────────

function git(root, args) {
  return execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

/** Write `server/prisma/schema` as it is at `ref` into a new temp folder; returns the folder. */
function exportSchemaAt(root, ref, into) {
  const files = git(root, ['ls-tree', '-r', '--name-only', ref, '--', SCHEMA_DIR])
    .split('\n')
    .filter((f) => f.endsWith('.prisma'));
  if (files.length === 0) throw new Error(`no ${SCHEMA_DIR}/*.prisma at ${ref}`);
  for (const file of files) {
    const target = join(into, file);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, git(root, ['show', `${ref}:${file}`]));
  }
  return join(into, SCHEMA_DIR);
}

function prismaCli(root) {
  const pkgPath = join(root, 'node_modules', 'prisma', 'package.json');
  if (!existsSync(pkgPath)) throw new Error('prisma is not installed (node_modules/prisma): run npm install');
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  const bin = typeof pkg.bin === 'string' ? pkg.bin : pkg.bin?.prisma;
  return join(root, 'node_modules', 'prisma', bin);
}

/** `prisma migrate diff --from-schema <a> --to-schema <b> --script`, datamodel to datamodel. */
function diffSchemaFolders(root, fromDir, toDir) {
  return execFileSync(process.execPath, [prismaCli(root), 'migrate', 'diff', '--from-schema', fromDir, '--to-schema', toDir, '--script'], {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    stdio: ['ignore', 'pipe', 'pipe'],
    env: { ...process.env, DATABASE_URL: NO_DATABASE_URL, DIRECT_DATABASE_URL: NO_DATABASE_URL, PRISMA_HIDE_UPDATE_MESSAGE: '1' },
  });
}

/** Every *.prisma file of a schema folder, joined (sorted by path, so the result is stable). */
function readSchemaFolder(dir) {
  return readdirSync(dir, { recursive: true })
    .map(String)
    .filter((file) => file.endsWith('.prisma'))
    .sort()
    .map((file) => readFileSync(join(dir, file), 'utf8'))
    .join('\n');
}

/**
 * The SQL of the datamodel-to-datamodel diff, plus what the SQL cannot show
 * (unsupportedTypeChanges of the two folders).
 * @returns {{ sql: string, base: string | null, unsupportedChanges: { field: string, from: string, to: string }[] }}
 */
function schemaDiff(root, { base, fromDir, toDir }) {
  const diff = (from) => ({
    sql: diffSchemaFolders(root, from, toDir),
    unsupportedChanges: unsupportedTypeChanges(readSchemaFolder(from), readSchemaFolder(toDir)),
  });
  if (fromDir) return { ...diff(resolve(root, fromDir)), base: null };
  const sha = git(root, ['rev-parse', '--verify', `${base}^{commit}`]).trim();
  const tmp = mkdtempSync(join(tmpdir(), 'schema-additive-'));
  try {
    return { ...diff(exportSchemaAt(root, sha, tmp)), base: sha };
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

function defaultBase(root) {
  try {
    return git(root, ['merge-base', 'HEAD', DEFAULT_BASE_BRANCH]).trim();
  } catch {
    throw new Error(`cannot find the merge base of HEAD and ${DEFAULT_BASE_BRANCH}: pass --base <git ref>`);
  }
}

/**
 * The reviewer header --out keeps: everything above the marker line, or, for a file that has
 * no marker yet, the whole file when it holds comments only (a hand-written header).
 */
function headerFor(file, label) {
  if (!existsSync(file)) return `-- ${label}\n-- Additive schema diff (prisma migrate diff, datamodel to datamodel; no database was read).\n--\n`;
  const text = readFileSync(file, 'utf8');
  const parts = splitGeneratedFile(text);
  if (parts) return parts.header;
  if (splitSqlStatements(text).length > 0) {
    throw new Error(`${label} holds SQL but no marker line; refusing to overwrite it (delete it, or put the marker line above the SQL)`);
  }
  return text.endsWith('\n') || text === '' ? text : `${text}\n`;
}

function parseArgs(argv) {
  const args = { quiet: false };
  const valued = { '--base': 'base', '--from-dir': 'fromDir', '--to-dir': 'toDir', '--sql': 'sql', '--out': 'out', '--check': 'check', '--root': 'root' };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--quiet') args.quiet = true;
    else if (arg === '--help' || arg === '-h') args.help = true;
    else if (valued[arg]) {
      if (argv[i + 1] === undefined) throw new Error(`${arg} needs a value`);
      args[valued[arg]] = argv[(i += 1)];
    } else throw new Error(`unknown argument ${arg}`);
  }
  return args;
}

function report(result, label, { knownDriftApplied = false } = {}) {
  const count = (pattern) => result.statements.filter((s) => !result.ignored.includes(s) && pattern.test(s.text)).length;
  const where = (line) => (line > 0 ? `line ${line}` : 'schema');
  for (const s of result.ignored) console.error(`ignored (KNOWN_DRIFT pair), line ${s.line}: ${s.text.split('\n')[0]}`);
  for (const w of result.warnings) console.error(`warning ${w.rule}, line ${w.line}: ${WARNINGS[w.rule]}\n    ${w.statement.split('\n')[0]}`);
  if (!result.ok) {
    for (const v of result.violations) console.error(`NOT ADDITIVE ${v.rule}, ${where(v.line)}: ${RULES[v.rule]}\n    ${v.statement.split('\n').join('\n    ')}`);
    console.error(`\ncheck-schema-additive: ${result.violations.length} change(s) of ${label} are not additive.`);
    return;
  }
  console.error(
    `check-schema-additive: ${label} is additive only: ${count(/^CREATE\s+TABLE/i)} CREATE TABLE, ` +
      `${count(/^ALTER\s+TABLE[\s\S]*?\bADD\s+COLUMN\b/i)} ALTER TABLE ... ADD COLUMN, ${count(/^CREATE\s+(UNIQUE\s+)?INDEX/i)} CREATE INDEX, ` +
      `${count(/^ALTER\s+TABLE[\s\S]*?\bADD\s+CONSTRAINT\b/i)} ADD CONSTRAINT; ` +
      (knownDriftApplied
        ? `${result.ignored.length} statement(s) ignored as KNOWN_DRIFT pairs.`
        : 'no Unsupported type changed; KNOWN_DRIFT is not applied to a schema-to-schema diff.'),
  );
}

/**
 * @param {string[]} argv
 * @param {{ schemaDiff?: typeof schemaDiff }} [deps] the tests replace the Prisma run
 * @returns {number} the exit code
 */
export function main(argv, deps = {}) {
  const runDiff = deps.schemaDiff ?? schemaDiff;
  const args = parseArgs(argv);
  if (args.help) {
    const lines = readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1);
    console.log(lines.slice(0, lines.findIndex((line) => !line.startsWith('//'))).join('\n'));
    return 0;
  }
  const root = resolve(args.root ?? join(dirname(fileURLToPath(import.meta.url)), '..'));
  const toDir = resolve(root, args.toDir ?? SCHEMA_DIR);

  if (args.sql) {
    // The only mode that reads KNOWN_DRIFT: the pairs come from introspection of a database.
    const knownDriftFile = join(root, KNOWN_DRIFT_PATH);
    const knownDrift = existsSync(knownDriftFile) ? parseKnownDrift(readFileSync(knownDriftFile, 'utf8')) : [];
    for (const entry of knownDrift) {
      if (!entry.create || entry.create.split(/…|\.\.\./).length !== 2) {
        console.error(
          `warning: the ${KNOWN_DRIFT_PATH} row of ${entry.name} records no \`CREATE INDEX … (…)\` definition in its second column, so it excuses nothing.`,
        );
      }
    }
    const sql = readFileSync(args.sql === '-' ? 0 : resolve(args.sql), 'utf8');
    const result = classifyAdditive(sql, { knownDrift });
    report(result, args.sql === '-' ? 'the SQL on stdin' : args.sql, { knownDriftApplied: true });
    return result.ok ? 0 : 1;
  }

  // Schema folder to schema folder: no KNOWN_DRIFT (nothing is introspected), plus the Unsupported comparison.
  const classify = (diff) => withUnsupportedChanges(classifyAdditive(diff.sql), diff.unsupportedChanges);

  if (args.check) {
    const file = resolve(args.check);
    const parts = splitGeneratedFile(readFileSync(file, 'utf8'));
    if (!parts || !parts.base) {
      console.error(`check-schema-additive: ${args.check} has no marker line or no "-- base: <commit>" line; write it with --out.`);
      return 1;
    }
    const fresh = runDiff(root, { base: args.base ?? parts.base, toDir });
    const result = classify(fresh);
    report(result, 'the schema diff');
    if (fresh.sql.trimEnd() !== parts.sql.trimEnd()) {
      console.error(`check-schema-additive: ${args.check} is stale: run node scripts/check-schema-additive.mjs --base ${parts.base} --out ${args.check}`);
      return 1;
    }
    return result.ok ? 0 : 1;
  }

  const fresh = runDiff(root, { base: args.base ?? (args.fromDir ? null : defaultBase(root)), fromDir: args.fromDir, toDir });
  if (!args.quiet) process.stdout.write(fresh.sql);
  const result = classify(fresh);
  report(result, 'the schema diff');
  if (args.out && result.ok) {
    const file = resolve(args.out);
    writeFileSync(file, renderGeneratedFile({ header: headerFor(file, args.out), base: fresh.base, sql: fresh.sql }));
    console.error(`check-schema-additive: wrote ${args.out}`);
  } else if (args.out) {
    console.error(`check-schema-additive: ${args.out} NOT written (the diff is not additive).`);
  }
  return result.ok ? 0 : 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (error) {
    console.error(`check-schema-additive: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
